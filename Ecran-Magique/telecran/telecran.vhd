library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library pll;
use pll.all;

entity telecran is
    port (
        -- FPGA
        i_clk_50: in std_logic;

        -- HDMI
        io_hdmi_i2c_scl       : inout std_logic;
        io_hdmi_i2c_sda       : inout std_logic;
        o_hdmi_tx_clk        : out std_logic;
        o_hdmi_tx_d          : out std_logic_vector(23 downto 0);
        o_hdmi_tx_de         : out std_logic;
        o_hdmi_tx_hs         : out std_logic;
        i_hdmi_tx_int        : in std_logic;
        o_hdmi_tx_vs         : out std_logic;

        -- KEYs
        i_rst_n : in std_logic;
		  
		-- LEDs
		o_leds : out std_logic_vector(9 downto 0);
		o_de10_leds : out std_logic_vector(7 downto 0);

		-- Coder
		i_left_ch_a : in std_logic;
		i_left_ch_b : in std_logic;
		i_left_pb : in std_logic;
		i_right_ch_a : in std_logic;
		i_right_ch_b : in std_logic;
		i_right_pb : in std_logic
    );
end entity telecran;

architecture rtl of telecran is
	component I2C_HDMI_Config 
		port (
			iCLK : in std_logic;
			iRST_N : in std_logic;
			I2C_SCLK : out std_logic;
			I2C_SDAT : inout std_logic;
			HDMI_TX_INT  : in std_logic
		);
	 end component;
	 
	component pll 
		port (
			refclk : in std_logic;
			rst : in std_logic;
			outclk_0 : out std_logic;
			locked : out std_logic
		);
	end component;

	component hdmi_controler
		generic (
			h_res 	: positive := 720;
			v_res 	: positive := 480;
			h_sync	: positive := 61;
			h_fp	: positive := 58;
			h_bp	: positive := 18;
			v_sync	: positive := 5;
			v_fp	: positive := 30;
			v_bp	: positive := 9
		);
		port (
			i_clk  		: in std_logic;
			i_rst_n 	: in std_logic;
			o_hdmi_hs   : out std_logic;
			o_hdmi_vs   : out std_logic;
			o_hdmi_de   : out std_logic;
			o_pixel_en : out std_logic;
			o_pixel_address : out natural range 0 to (h_res * v_res - 1);
			o_x_counter : out natural range 0 to (h_res - 1);
			o_y_counter : out natural range 0 to (v_res - 1)
		);
	end component;

	component encoder
		generic (
			PERIOD_S_EN : natural := 500000;
			WIDTH : natural := 10
		);
		port (
			i_clk   : in std_logic;
			i_rst_n : in std_logic;
			i_A     : in std_logic;
			i_B     : in std_logic;
			o_leds  : out std_logic_vector(WIDTH-1 downto 0)
		);
	end component;

	component dpram is
		generic
		(
			mem_size    : natural := 720 * 480;
			data_width  : natural := 8
		);
		port
		(
			i_clk_a        : in std_logic;
			i_clk_b        : in std_logic;

			i_data_a    : in std_logic_vector(data_width-1 downto 0);
			i_data_b    : in std_logic_vector(data_width-1 downto 0);
			i_addr_a    : in natural range 0 to mem_size-1;
			i_addr_b    : in natural range 0 to mem_size-1;
			i_we_a      : in std_logic := '1';
			i_we_b      : in std_logic := '1';
			o_q_a       : out std_logic_vector(data_width-1 downto 0);
			o_q_b       : out std_logic_vector(data_width-1 downto 0)
		);
	end dpram;



    constant h_res : natural := 720;
    constant v_res : natural := 480;
    -- 270000 @ 27 MHz = 10 ms
    constant enc_period : natural := 270000;
    constant enc_width : natural := 10;

	signal s_clk_27 : std_logic;
	signal s_rst_n : std_logic;	-- holds reset as long as pll is not locked

	signal s_x_counter : natural range 0 to (h_res - 1);
	signal s_y_counter : natural range 0 to (v_res - 1);
	signal s_pixel_address : natural range 0 to (h_res * v_res - 1);

	signal s_x_pixel : std_logic_vector(enc_width-1 downto 0);
	signal s_y_pixel : std_logic_vector(enc_width-1 downto 0);
	signal s_cursor_address : natural range 0 to (h_res * v_res - 1);
	signal s_cursor_valid : std_logic;
	signal s_ram_q_b : std_logic_vector(0 downto 0);
begin
	o_leds <= (others => '0');
	o_de10_leds <= (others => '0');

	cursor_address : process(s_x_pixel, s_y_pixel)
		variable x : natural;
		variable y : natural;
	begin
		x := to_integer(unsigned(s_x_pixel));
		y := to_integer(unsigned(s_y_pixel));
		if (x < h_res) and (y < v_res) then
			s_cursor_address <= x + (y * h_res);
			s_cursor_valid <= '1';
		else
			s_cursor_address <= 0;
			s_cursor_valid <= '0';
		end if;
	end process cursor_address;
	
	-- Frequency for HDMI is 27MHz generated by this PLL
	pll0 : component pll 
		port map (
			refclk => i_clk_50,
			rst => not(i_rst_n),
			outclk_0 => s_clk_27,
			locked => s_rst_n
		);

	-- Configures the ADV7513 for 480p
	I2C_HDMI_Config0 : component I2C_HDMI_Config 
		port map (
			iCLK => i_clk_50,
			iRST_N => i_rst_n,
			I2C_SCLK => io_hdmi_i2c_scl,
			I2C_SDAT => io_hdmi_i2c_sda,
			HDMI_TX_INT => i_hdmi_tx_int
	 );

	-- HDMI controller
	hdmi_controler0 : component hdmi_controler
		generic map (
			h_res => h_res,
			v_res => v_res
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			o_hdmi_hs => o_hdmi_tx_hs,
			o_hdmi_vs => o_hdmi_tx_vs,
			o_hdmi_de => o_hdmi_tx_de,
			o_pixel_en => open,
			o_pixel_address => s_pixel_address,
			o_x_counter => s_x_counter,
			o_y_counter => s_y_counter
		);

	o_hdmi_tx_clk <= s_clk_27;

	-- Left encoder -> horizontal
	encoder_left : component encoder
		generic map (
			PERIOD_S_EN => enc_period,
			WIDTH => enc_width
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			i_A => i_left_ch_a,
			i_B => i_left_ch_b,
			o_leds => s_x_pixel
		);

	-- Right encoder -> vertical
	encoder_right : component encoder
		generic map (
			PERIOD_S_EN => enc_period,
			WIDTH => enc_width
		)
		port map (
			i_clk => s_clk_27,
			i_rst_n => s_rst_n,
			i_A => i_right_ch_a,
			i_B => i_right_ch_b,
			o_leds => s_y_pixel
		);

	framebuffer : component dpram
		generic map (
			mem_size => h_res * v_res,
			data_width => 1
		)
		port map (
			i_clk_a => s_clk_27,
			i_clk_b => s_clk_27,
			i_data_a => "1",
			i_data_b => "0",
			i_addr_a => s_cursor_address,
			i_addr_b => s_pixel_address,
			i_we_a => s_cursor_valid,
			i_we_b => '0',
			o_q_a => open,
			o_q_b => s_ram_q_b
		);

	o_hdmi_tx_d <= x"FFFFFF" when s_ram_q_b(0) = '1' else x"000000";
	
end architecture rtl;
